// What the radio can play. Data only: the menu, the HUD and the player all read this
// list, so adding a station or a track means adding it here and nowhere else.
//
// A track's `file` is relative to the repository root and is published under the same
// path. `status: 'test'` marks audio that isn't finished music, and the interface says
// so. See docs/RADIO.md for what a final track needs.
export const RADIO_OFF = 'off';

// Radio Off while only test audio exists, so nobody hears a placeholder unasked.
// Worth revisiting once final music is installed.
export const DEFAULT_STATION = RADIO_OFF;

const GENERATED = 'MIT, generated by scripts/radio-test-tracks.mjs';

export const STATIONS = Object.freeze([
  {
    id: 'garage-rock',
    name: 'Garage Rock',
    tracks: [{ id: 'garage-rock-test', title: 'Garage Rock test loop', file: 'radio/test-tracks/garage-rock-test.wav', status: 'test', license: GENERATED }],
  },
  {
    id: 'synth-fm',
    name: 'Synth FM',
    tracks: [{ id: 'synth-fm-test', title: 'Synth FM test loop', file: 'radio/test-tracks/synth-fm-test.wav', status: 'test', license: GENERATED }],
  },
  {
    id: 'redline-radio',
    name: 'Redline Radio',
    tracks: [{ id: 'redline-radio-test', title: 'Redline Radio test loop', file: 'radio/test-tracks/redline-radio-test.wav', status: 'test', license: GENERATED }],
  },
  { id: RADIO_OFF, name: 'Radio Off', tracks: [] },
]);

export const stationById = (id, stations = STATIONS) => stations.find((station) => station.id === id);

export const hasTestAudio = (station) => !!station?.tracks.some((track) => track.status === 'test');

// Everything the radio publishes: its attribution, and every track named above.
export const RADIO_FILES = Object.freeze(['radio/ATTRIBUTION.md', ...STATIONS.flatMap((station) => station.tracks.map((track) => track.file))]);
