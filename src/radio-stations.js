// What the radio can play. Data only: the menu, the HUD and the player all read this
// list, so adding a station or a track means adding it here and nowhere else.
//
// A track's `file` is relative to the repository root and is published under the same
// path. `status: 'provisional'` marks built-in music that may be replaced later, and
// Options says so. See docs/RADIO.md for how to replace a track.
export const RADIO_OFF = 'off';

// The radio is something a player turns on, and a saved choice always wins over this.
export const DEFAULT_STATION = RADIO_OFF;

const GENERATED = 'MIT, generated by scripts/radio-test-tracks.mjs';

export const STATIONS = Object.freeze([
  {
    id: 'garage-rock',
    name: 'Garage Rock',
    tracks: [{ id: 'garage-rock-test', title: 'Garage Rock provisional loop', file: 'radio/test-tracks/garage-rock-test.wav', status: 'provisional', license: GENERATED }],
  },
  {
    id: 'synth-fm',
    name: 'Synth FM',
    tracks: [{ id: 'synth-fm-test', title: 'Synth FM provisional loop', file: 'radio/test-tracks/synth-fm-test.wav', status: 'provisional', license: GENERATED }],
  },
  {
    id: 'redline-radio',
    name: 'Redline Radio',
    tracks: [{ id: 'redline-radio-test', title: 'Redline Radio provisional loop', file: 'radio/test-tracks/redline-radio-test.wav', status: 'provisional', license: GENERATED }],
  },
  { id: RADIO_OFF, name: 'Radio Off', tracks: [] },
]);

export const stationById = (id, stations = STATIONS) => stations.find((station) => station.id === id);

export const hasProvisionalMusic = (station) => !!station?.tracks.some((track) => track.status === 'provisional');

// Everything the radio publishes: its attribution, and every track named above.
export const RADIO_FILES = Object.freeze(['radio/ATTRIBUTION.md', ...STATIONS.flatMap((station) => station.tracks.map((track) => track.file))]);
